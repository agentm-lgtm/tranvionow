<section class="tvw7k2-section" id="tvw7k2-story">
  <div class="tvw7k2-wrap">
    <span class="tvw7k2-kicker">Our Story</span>
    <h2>How Tranvionow grew from one borrowed barn</h2>
    <p class="tvw7k2-lead">Every studio has an origin story. Ours involves a rainstorm, a borrowed barn, two hundred folding chairs, and a promise made at midnight.</p>
    <div class="tvw7k2-timeline">
      <div class="tvw7k2-tl-item">
        <span class="tvw7k2-tl-year">2013 — The Barn Wedding</span>
        <h3>Where it all started</h3>
        <p>Our founder, Marta Ellison, planned her sister's wedding in a borrowed barn with no budget and a leaking roof. When the storm knocked the power out mid-dinner, guests ate by candlelight and called it the most beautiful evening of their lives. Marta realized that atmosphere is not bought — it is cared into being. She spent the next year apprenticing with two established planners and studying hospitality management at night.</p>
      </div>
      <div class="tvw7k2-tl-item">
        <span class="tvw7k2-tl-year">2015 — First Studio Season</span>
        <h3>Twelve weddings, one desk</h3>
        <p>Tranvionow officially opened with a single desk in a shared workspace and a calendar of twelve weddings. Every couple that year came through word of mouth. Three of those original couples still send holiday cards, and one of them now refers their own grown children to us — a full-circle moment we treasure.</p>
      </div>
      <div class="tvw7k2-tl-item">
        <span class="tvw7k2-tl-year">2018 — The Team Grows</span>
        <h3>From solo planner to small studio</h3>
        <p>After three seasons of turning couples away, Marta hired two associate planners — both trained in-house for a full year before leading their first wedding. That slow, careful apprenticeship model still defines how our team grows today. We would rather plan fewer weddings well than many weddings quickly.</p>
      </div>
      <div class="tvw7k2-tl-item">
        <span class="tvw7k2-tl-year">2021 — Destination Chapter</span>
        <h3>Weekends away, done properly</h3>
        <p>A couple asked us to plan a three-day celebration in a coastal village where none of the vendors spoke English. We said yes, learned an enormous amount, and came home with a destination planning framework we have refined ever since — local fixers, translated contracts, and rehearsal walkthroughs on video for family who could not travel early.</p>
      </div>
      <div class="tvw7k2-tl-item">
        <span class="tvw7k2-tl-year">2024 — Today</span>
        <h3>Two hundred celebrations and counting</h3>
        <p>Tranvionow has now guided more than two hundred weddings, elopements, and anniversary celebrations. The studio remains deliberately small: four planners, one coordinator bench, and a rule that no planner ever carries more than eight weddings in a season. The borrowed barn, by the way, still hosts one wedding a year — and we still plan it for free, as a thank-you to where we began.</p>
      </div>
    </div>
  </div>
